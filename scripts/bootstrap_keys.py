#!/usr/bin/env python3
"""Create the throwaway testnet keys for QorePass.

    python scripts/bootstrap_keys.py

Writes `keys/keys.env` (mode 600, gitignored) with two new mnemonics, and — if
the QoreChain QoreGuard run left its funder mnemonic on this machine — copies
that *reference* in so the new accounts can be funded with free test QOR. The
copy is a local convenience only: nothing from the other project's keys is ever
committed, and QorePass never re-uses its contract or code.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qorsdk import generate_mnemonic  # noqa: E402

KEYS = ROOT / "keys"
ENV = KEYS / "keys.env"
#: Optional: point at another local project's keys.env to borrow a funded
#: testnet account for the first transfer (free test QOR only).
PRIOR_ENV = Path(os.environ["QOREPASS_PRIOR_ENV"]) if os.environ.get("QOREPASS_PRIOR_ENV") else None


def prior_owner_mnemonic() -> str:
    if PRIOR_ENV is None or not PRIOR_ENV.exists():
        return ""
    match = re.search(r'^QORE_OWNER_MNEMONIC="?([^"\n]+)"?$', PRIOR_ENV.read_text(), re.M)
    return match.group(1) if match else ""


def main() -> int:
    KEYS.mkdir(exist_ok=True)
    existing: dict[str, str] = {}
    if ENV.exists():
        for line in ENV.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                key, value = line.split("=", 1)
                existing[key.strip()] = value.strip().strip('"')

    values = {
        "QOREPASS_ORGANIZER_MNEMONIC": existing.get("QOREPASS_ORGANIZER_MNEMONIC") or generate_mnemonic(),
        "QOREPASS_ISSUER_MNEMONIC": existing.get("QOREPASS_ISSUER_MNEMONIC") or generate_mnemonic(),
        "QOREPASS_FUNDER_MNEMONIC": existing.get("QOREPASS_FUNDER_MNEMONIC") or prior_owner_mnemonic(),
    }
    body = [
        "# QorePass throwaway testnet keys (qorechain-diana). No value. Never commit.",
        "# Generated by scripts/bootstrap_keys.py.",
    ]
    for key, value in values.items():
        body.append(f'{key}="{value}"')
    ENV.write_text("\n".join(body) + "\n")
    ENV.chmod(0o600)

    print(f"wrote {ENV} (mode 600)")
    print("  organizer, issuer: new mnemonics")
    print("  funder:", "existing testnet funder" if values["QOREPASS_FUNDER_MNEMONIC"] else "MISSING - set QOREPASS_FUNDER_MNEMONIC yourself")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
